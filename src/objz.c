const GdObjZ *gd_objz_find(int id)
{
    int lo = 0, hi = (int)(sizeof k_z / sizeof k_z[0]) - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (k_z[mid].id == id) return &k_z[mid];
        if (k_z[mid].id < id) lo = mid + 1; else hi = mid - 1;
    }
    return 0;
}
