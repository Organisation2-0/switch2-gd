{
    int lo = 0, hi = gd_children_count - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (gd_children[mid].id < id) lo = mid + 1; else hi = mid - 1;
    }
    int n = 0;
    while (lo + n < gd_children_count && gd_children[lo + n].id == id) n++;
    *count = n;
    return n ? &gd_children[lo] : NULL;
}
