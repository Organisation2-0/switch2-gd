// Writes src/phystab.c (object type and hitbox per id).
//   node tools/genphys.js <objects_2.2081.json> src/phystab.c
// The input is the object table of gd-levelgen (https://github.com/kholkink/gd-levelgen, MIT, see
// vendor/gd-levelgen-LICENSE.txt), read out of Geometry Dash 2.2081.
const fs = require('fs');
const [input, output] = process.argv.slice(2);
const objects = JSON.parse(fs.readFileSync(input, 'utf8').replace(/\bNaN\b/g, 'null')).objects;

// type names of the game -> the numbers apply_phys() in game.c knows
const code = {
    Solid: 0, Hazard: 2, AnimatedHazard: 2, InverseGravityPortal: 3, NormalGravityPortal: 4, ShipPortal: 5,
    CubePortal: 6, YellowJumpPad: 8, PinkJumpPad: 9, GravityPad: 10, YellowJumpRing: 11, PinkJumpRing: 12,
    GravityRing: 13, InverseMirrorPortal: 14, NormalMirrorPortal: 15, BallPortal: 16, RegularSizePortal: 17,
    MiniSizePortal: 18, UfoPortal: 19, Breakable: 21, DualPortal: 23, SoloPortal: 24, Slope: 25, WavePortal: 26,
    RobotPortal: 27, GreenRing: 29, SpiderPortal: 33, RedJumpPad: 34, RedJumpRing: 35, SwingPortal: 40,
    GravityTogglePortal: 41, TeleportPortal: 42, SpiderPad: 43, DropRing: 44, DashRing: 45, GravityDashRing: 46,
    SpiderOrb: 47, TeleportOrb: 48, CustomRing: 49,
};
const speedPortals = [200, 201, 202, 203, 1334];
// half spikes drawn beside the middle of their cell: horizontal offset of the box (from OpenGD)
const offsetX = { 243: -5, 244: 5, 422: -5, 447: -5, 1720: -5, 1721: 5, 1726: -5, 1729: -5 };

// Marked as blocks in the data (their type was never set) although they only decorate: the lines of
// the 3D look (persp_outline), the buttons of the area triggers and a particle sprite.
const decoration = [[506, 640], [902, 902], [943, 951], [980, 988], [1024, 1032], [1063, 1071], [1529, 1529],
    [1531, 1540], [1552, 1560], [3006, 3021], [3800, 3800]];

const num = (v) => Number(v.toFixed(3));
const rows = [];
for (const o of Object.values(objects).sort((a, b) => a.id - b.id)) {
    const type = speedPortals.includes(o.id) ? 20 : code[o.type];
    if (type === undefined || o.id === 3643) continue;   // 3643: the toggle block, handled in game.c
    if (decoration.some(([from, to]) => o.id >= from && o.id <= to)) continue;
    const sprite = o.sprite_size || [30, 30];
    const base = [0, 1].map((i) => (o.size_override[i] === null ? sprite[i] : o.size_override[i]));
    const w = base[0] * o.hitbox_mul[0], h = base[1] * o.hitbox_mul[1], x = offsetX[o.id] || 0;
    rows.push(`    {${o.id}, ${type}, ${num(w)}, ${num(h)}, ${num(x - w / 2)}, ${num(-h / 2)}, ${num(o.radius || 0)}},`);
}
fs.writeFileSync(output, `// SPDX-License-Identifier: GPL-3.0-or-later
// Object type + hitbox table, generated by tools/genphys.js. Do not edit by hand.
// Data: gd-levelgen (https://github.com/kholkink/gd-levelgen), MIT License,
// Copyright (c) 2026 NoJokes (kholkink), see vendor/gd-levelgen-LICENSE.txt; read out of Geometry
// Dash 2.2081. The side offsets of a few half spikes come from OpenGD (GPL-3.0).
// w,h: size of the box, x,y: its lower left corner relative to the object, radius: round hitbox.
#include <stddef.h>
#include "phystab.h"
const GdPhys gd_phys[] = {
${rows.join('\n')}
};
const int gd_phys_count = sizeof gd_phys / sizeof gd_phys[0];


const GdPhys *gd_phys_find(int id)
{
    int lo = 0, hi = gd_phys_count - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (gd_phys[mid].id == id) return &gd_phys[mid];
        if (gd_phys[mid].id < id) lo = mid + 1; else hi = mid - 1;
    }
    return NULL;
}
`);
console.log(rows.length, 'objects with a hitbox');
